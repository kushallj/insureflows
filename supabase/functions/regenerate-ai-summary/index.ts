// Placeholder edge function: returns a canned AI summary and stores it on the contact.
// A real AI service will replace this later — the UI is already wired up.
import { createClient } from "https://esm.sh/@supabase/supabase-js@2.49.4";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type",
};

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { contact_id } = await req.json();
    if (!contact_id) throw new Error("contact_id required");

    const authHeader = req.headers.get("Authorization") ?? "";
    const supabase = createClient(
      Deno.env.get("SUPABASE_URL")!,
      Deno.env.get("SUPABASE_PUBLISHABLE_KEY") ?? Deno.env.get("SUPABASE_ANON_KEY")!,
      { global: { headers: { Authorization: authHeader } } },
    );

    const { data: contact, error: readErr } = await supabase
      .from("contacts")
      .select(
        "id,name,city,occupation,age,pipeline_stage,tags,lead_score,preferred_channel",
      )
      .eq("id", contact_id)
      .maybeSingle();
    if (readErr) throw readErr;
    if (!contact) throw new Error("Contact not found");

    const parts: string[] = [];
    parts.push(
      `${contact.name}${contact.age ? `, ${contact.age}` : ""}${
        contact.occupation ? `, ${contact.occupation}` : ""
      }${contact.city ? ` in ${contact.city}` : ""}.`,
    );
    parts.push(
      `Currently in the "${contact.pipeline_stage}" stage with a lead score of ${contact.lead_score}. Prefers ${contact.preferred_channel}.`,
    );
    if (Array.isArray(contact.tags) && contact.tags.length) {
      parts.push(`Tags: ${(contact.tags as string[]).join(", ")}.`);
    }
    parts.push(
      "Recommended next step: reach out on their preferred channel with a personalised renewal or product recommendation.",
    );
    parts.push("— Generated by placeholder AI (stub). Connect a real model to replace.");

    const ai_summary = parts.join(" ");

    const { error: updErr } = await supabase
      .from("contacts")
      .update({ ai_summary })
      .eq("id", contact_id);
    if (updErr) throw updErr;

    return new Response(
      JSON.stringify({ ok: true, ai_summary, source: "stub" }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } },
    );
  } catch (e) {
    const message = e instanceof Error ? e.message : String(e);
    return new Response(JSON.stringify({ ok: false, error: message }), {
      status: 400,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
